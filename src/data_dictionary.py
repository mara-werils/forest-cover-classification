"""Generate docs/DATA_DICTIONARY.md from config.py and the data itself.

Everything in the document is derived - column order, storage dtypes,
valid ranges, observed statistics, soil decoding - so it can be rebuilt
after any change with:

    python -m src.data_dictionary
"""

import pandas as pd

from src import config, data_loader, predict

OUTPUT = config.ROOT_DIR / "docs" / "DATA_DICTIONARY.md"

DESCRIPTIONS = {
    "Elevation": ("m", "Elevation above sea level"),
    "Aspect": ("deg azimuth", "Compass direction the slope faces (0 = N, 90 = E)"),
    "Slope": ("deg", "Steepness of the slope"),
    "Horizontal_Distance_To_Hydrology": ("m", "Horizontal distance to the nearest surface water"),
    "Vertical_Distance_To_Hydrology": ("m", "Height above (+) or below (-) the nearest water"),
    "Horizontal_Distance_To_Roadways": ("m", "Horizontal distance to the nearest road"),
    "Hillshade_9am": ("index 0-255", "Illumination at 9am on the summer solstice"),
    "Hillshade_Noon": ("index 0-255", "Illumination at noon on the summer solstice"),
    "Hillshade_3pm": ("index 0-255", "Illumination at 3pm on the summer solstice"),
    "Horizontal_Distance_To_Fire_Points": ("m", "Horizontal distance to the nearest wildfire "
                                                "ignition point"),
}


def _fmt(value):
    if pd.isna(value):
        return ""
    return f"{value:,.0f}" if float(value).is_integer() else f"{value:,.1f}"


def numeric_section(df):
    dtypes = data_loader.optimized_dtypes()
    lines = [
        "| # | Column | Unit | Meaning | Stored as | Valid range | Observed min | Median | "
        "Observed max | Prediction form limits |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    for i, col in enumerate(config.NUMERIC_COLS, start=1):
        unit, meaning = DESCRIPTIONS[col]
        low, high = config.VALID_RANGES.get(col, (None, None))
        valid = "-" if low is None and high is None else f"{low} .. {high if high else 'inf'}"
        form = predict.INPUT_LIMITS[col]
        series = df[col]
        lines.append(
            f"| {i} | `{col}` | {unit} | {meaning} | `{dtypes[col]}` | {valid} | "
            f"{_fmt(series.min())} | {_fmt(series.median())} | {_fmt(series.max())} | "
            f"{form[0]} .. {form[1]} |"
        )
    return lines


def categorical_section(df):
    counts = df[config.WILDERNESS].value_counts()
    lines = [
        "| Code | One-hot column | Wilderness area | Cells | Share |",
        "|---|---|---|---|---|",
    ]
    for code, name in config.WILDERNESS_AREAS.items():
        n = int(counts.get(code, 0))
        lines.append(f"| {code} | `Wilderness_Area{code}` | {name} | {n:,} | "
                     f"{100 * n / len(df):.1f}% |")
    return lines


def soil_section(df):
    counts = df[config.SOIL].value_counts()
    dominant = (df.groupby(config.SOIL)[config.TARGET]
                .agg(lambda s: s.value_counts().idxmax()))
    lines = [
        "| Soil | ELU code | Climatic zone | Geologic zone | Description | Cells | "
        "Most common cover type |",
        "|---|---|---|---|---|---|---|",
    ]
    for soil_id, (elu, description) in config.SOIL_TYPES.items():
        climatic = config.CLIMATIC_ZONES[int(str(elu)[0])]
        geologic = config.GEOLOGIC_ZONES[int(str(elu)[1])]
        n = int(counts.get(soil_id, 0))
        top = config.COVER_TYPES[int(dominant[soil_id])] if soil_id in dominant else "-"
        lines.append(f"| {soil_id} | {elu} | {climatic} | {geologic} | {description} | "
                     f"{n:,} | {top} |")
    return lines


def target_section(df):
    counts = df[config.TARGET].value_counts()
    elevation = df.groupby(config.TARGET)["Elevation"].median()
    lines = ["| Code | Cover type | Cells | Share | Median elevation, m |",
             "|---|---|---|---|---|"]
    for code, name in config.COVER_TYPES.items():
        n = int(counts.get(code, 0))
        lines.append(f"| {code} | {name} | {n:,} | {100 * n / len(df):.2f}% | "
                     f"{_fmt(elevation.get(code))} |")
    return lines


def build_markdown(df):
    """The whole document as one string."""
    parts = [
        "# Data dictionary: UCI Covertype",
        "",
        "_Generated by `python -m src.data_dictionary` from `src/config.py` and "
        f"`{config.PARQUET_PATH.relative_to(config.ROOT_DIR).as_posix()}`; do not edit by hand._",
        "",
        f"* Rows: **{len(df):,}** cells of 30 x 30 m in the Roosevelt National Forest, "
        "Colorado; no missing values.",
        f"* Raw file: {len(config.RAW_COLUMNS)} columns = {len(config.NUMERIC_COLS)} numeric + "
        f"{len(config.WILDERNESS_COLS)} one-hot wilderness + {len(config.SOIL_COLS)} one-hot "
        "soil + target. The project collapses the two one-hot blocks into the integer "
        f"columns `{config.WILDERNESS}` (1-4) and `{config.SOIL}` (1-40).",
        f"* Source: <{config.DATA_SOURCE_PAGE}> (Blackard & Dean, CC BY 4.0).",
        "",
        "## Numeric features",
        "",
        "Valid range = physical limits used by the audit (`config.VALID_RANGES`); prediction "
        "form limits = what the console menu and the dashboard accept "
        "(`predict.INPUT_LIMITS`).",
        "",
        *numeric_section(df),
        "",
        "## Wilderness areas",
        "",
        *categorical_section(df),
        "",
        "## Soil types",
        "",
        "The 4-digit USFS ELU code encodes the climatic zone (first digit) and the geologic "
        "zone (second digit); the SQLite schema stores both as foreign keys of `soil_type`.",
        "",
        *soil_section(df),
        "",
        f"## Target: `{config.TARGET}`",
        "",
        *target_section(df),
        "",
    ]
    return "\n".join(parts)


def write_dictionary(df=None, path=None):
    df = df if df is not None else data_loader.load_parquet()
    path = path or OUTPUT
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(build_markdown(df))
    return path


if __name__ == "__main__":
    print(f"Written {write_dictionary()}")
